@node_app.command(name="list")
def list_nodes_cmd(
    path: str = typer.Argument(
        ".",
        help="Path to repository or project (defaults to current directory)",
    ),
) -> None:
    """List all detected graph nodes and handlers across the project."""
    from rich import box
    from rich.table import Table

    project_dir = Path(path).resolve()
    with console.status(f"[bold cyan]Scanning nodes in {project_dir}...[/bold cyan]"):
        result = scan_repository(str(project_dir))

    nodes_seen = set()
    rows = []
    for g in result.graphs:
        for n in g.nodes:
            key = (g.graph_var, n.name)
            if key not in nodes_seen:
                nodes_seen.add(key)
                rel_file = Path(n.file_path).name
                llm_calls = len(n.agent_def.llm_calls) if n.agent_def else 0
                tools = len(n.agent_def.tools_bound) if n.agent_def else (len(n.tool_node_def.tools) if n.tool_node_def else 0)
                rows.append((g.graph_var, n.name, n.handler, f"{rel_file}:{n.line_number}", str(llm_calls), str(tools)))

    if not rows:
        console.print("[yellow]No LangGraph nodes detected in this project.[/yellow]")
        return

    t = Table(box=box.SIMPLE, show_header=True, header_style="bold dim")
    t.add_column("Graph", style="dim")
    t.add_column("Node Name", style="bold cyan")
    t.add_column("Handler", style="white")
    t.add_column("Location", style="dim")
    t.add_column("LLMs", justify="center", style="magenta")
    t.add_column("Tools", justify="center", style="yellow")

    for r in rows:
        t.add_row(*r)

    console.print(f"\n[bold white]Detected Nodes ({len(rows)})[/bold white]\n")
    console.print(t)
    console.print("\n[dim]Run any node in isolation with:[/dim]")
    console.print("  [bold]cz node run <node-name> --input '{\"key\": \"value\"}'[/bold]")
    console.print("  [bold]cz node run <node-name> --from-run <execution-id>[/bold]\n")


@node_app.command(name="run")
@app.command(name="debug")
def run_node_cmd(
    node_name: str = typer.Argument(
        ...,
        help="Name of the node to execute in isolation (e.g. planner, search, writer, verify_information)",
    ),
    from_run: Optional[str] = typer.Option(
        None,
        "--from-run",
        "-r",
        help="Execution ID from which to pull the exact captured input state",
    ),
    input_str: Optional[str] = typer.Option(
        None,
        "--input",
        "-i",
        help="JSON string representing the input state payload",
    ),
    input_file: Optional[Path] = typer.Option(
        None,
        "--input-file",
        "-f",
        help="Path to JSON file containing the input state payload",
    ),
    graph: Optional[str] = typer.Option(
        None,
        "--graph",
        "-g",
        help="Target python file or compiled graph reference (e.g. app.py or app.py:app)",
    ),
    path: str = typer.Option(
        ".",
        "--path",
        "-p",
        help="Project directory containing the node and .cohzen store",
    ),
    no_record: bool = typer.Option(
        False,
        "--no-record",
        help="Do not save this isolated debug run into Cohzen executions store",
    ),
    verbose: bool = typer.Option(
        False,
        "--verbose",
        "-v",
        help="Show verbose output with full input/output structures",
    ),
) -> None:
    """Execute a single graph node directly in isolation with custom or recorded inputs."""
    project_dir = Path(path).resolve()
    db_path = _find_db(str(project_dir))

    # Resolve input state
    input_state: Any = None
    if from_run:
        try:
            input_state = get_node_input_from_run(from_run, node_name, db_path=db_path)
            console.print(f"[dim]Loaded captured input for node [bold cyan]{node_name}[/bold cyan] from execution [bold]{from_run}[/bold][/dim]")
        except Exception as e:
            console.print(f"[bold red]Error fetching input from run {from_run}:[/bold red] {e}")
            return
    elif input_file:
        if not input_file.is_file():
            console.print(f"[bold red]Error:[/bold red] Input file {input_file} not found.")
            return
        try:
            input_state = json.loads(input_file.read_text(encoding="utf-8"))
        except Exception as e:
            console.print(f"[bold red]Error parsing JSON from {input_file}:[/bold red] {e}")
            return
    elif input_str:
        try:
            input_state = json.loads(input_str)
        except json.JSONDecodeError:
            input_state = input_str
    else:
        input_state = {}

    console.print(f"\n[bold white]Running Isolated Node:[/bold white] [bold cyan]{node_name}[/bold cyan]")
    console.print(f"[dim]Executing handler directly without running the complete graph...[/dim]\n")

    res = run_isolated_node(
        node_name=node_name,
        input_state=input_state,
        project_dir=project_dir,
        graph_target=graph,
        record=not no_record,
    )

    # Render results
    status_icon = "[bold green]✓ COMPLETED[/bold green]" if res.status == "completed" else "[bold red]✗ FAILED[/bold red]"
    console.print(f"Status:   {status_icon}")
    console.print(f"Duration: [bold cyan]{res.duration_ms:.1f}ms[/bold cyan]")
    if res.handler_name:
        console.print(f"Handler:  [dim]{res.handler_name} ({Path(res.file_path).name if res.file_path else ''})[/dim]")
    if res.execution_id and not no_record:
        console.print(f"Run ID:   [dim]{res.execution_id} (recorded)[/dim]")
    if res.reason:
        console.print(f"Why:      [italic cyan]{res.reason}[/italic cyan]")
    if res.error:
        console.print(f"[bold red]Error:[/bold red]    {res.error}")

    from rich.panel import Panel
    from rich.json import JSON

    # Print Input
    input_formatted = JSON(json.dumps(res.input_state, indent=2, default=str)) if isinstance(res.input_state, (dict, list)) else str(res.input_state)
    console.print(Panel(input_formatted, title=f"[bold]📥 Input Passed to {node_name}[/bold]", border_style="cyan"))

    # Print Output
    if res.output_state is not None:
        output_formatted = JSON(json.dumps(res.output_state, indent=2, default=str)) if isinstance(res.output_state, (dict, list)) else str(res.output_state)
        console.print(Panel(output_formatted, title=f"[bold]📤 Output Generated by {node_name}[/bold]", border_style="green"))

    # Print child spans if any
    if res.child_spans:
        console.print(f"\n[bold dim]Internal Operations ({len(res.child_spans)}):[/bold dim]")
        for sp in res.child_spans:
            kind_badge = f"[{sp.kind.upper()}]"
            console.print(f"  • {kind_badge} [bold]{sp.name}[/bold] ({format_duration(sp.duration_ms)})")
    console.print()


@app.command(name="scan")
def scan(
    path: str = typer.Argument(
        ".",
        help="Path to repository or directory to scan (defaults to current directory)",
    ),
    format: OutputFormat = typer.Option(
        OutputFormat.TABLE,
        "--format",
        "-f",
        help="Output format: table (rich interactive terminal), json (system manifest), or mermaid (diagram)",
    ),
    mermaid: bool = typer.Option(
        False,
        "--mermaid",
        help="Shortcut to output Mermaid diagram (equivalent to -f mermaid)",
    ),
    json_output_flag: bool = typer.Option(
        False,
        "--json",
        help="Shortcut to output Cohzen Manifest JSON (equivalent to -f json)",
    ),
    output: Optional[Path] = typer.Option(
        None,
        "--output",
        "-o",
        help="Write output to a specified file instead of stdout",
    ),
    verbose: bool = typer.Option(
        False,
        "--verbose",
        "-v",
        help="Display detailed debugging info during scan",
    ),
    view: bool = typer.Option(
        False,
        "--view",
        help="Open an interactive graphical visualizer in the default browser",
    ),
) -> None:
    """Scan a codebase to reconstruct LangGraph architecture and produce a system manifest."""
    if mermaid:
        format = OutputFormat.MERMAID
    elif json_output_flag:
        format = OutputFormat.JSON

    if format == OutputFormat.TABLE and not output and not view:
        with console.status(f"[bold cyan]Scanning repository for LangGraph architectures at {path}...[/bold cyan]"):
            result = scan_repository(path, verbose=verbose)
    else:
        result = scan_repository(path, verbose=verbose)

    if view:
        from cz.formatters.viewer import open_in_browser
        viewer_path = open_in_browser(result)
        console.print(f"[bold green]✔ Opened interactive architecture visualizer in browser ({viewer_path})[/bold green]")
        return

    # Format the result
    if format == OutputFormat.TABLE:
        if output:
            file_console = Console(record=True, width=120)
            print_console_report(result, console=file_console)
            output.write_text(file_console.export_text(), encoding="utf-8")
            console.print(f"[green]✔ Saved scan table report to {output}[/green]")
        else:
            print_console_report(result, console=console)

    elif format == OutputFormat.JSON:
        json_output = format_json(result)
        if output:
            output.write_text(json_output, encoding="utf-8")
            console.print(f"[green]✔ Saved JSON manifest to {output}[/green]")
        else:
            print(json_output)

    elif format == OutputFormat.MERMAID:
        mermaid_output = format_mermaid(result)
        if output:
            output.write_text(mermaid_output, encoding="utf-8")
            console.print(f"[green]✔ Saved Mermaid diagram to {output}[/green]")
        else:
            print(mermaid_output)


@app.command(name="audit")
def audit(
    path: str = typer.Argument(
        ".",
        help="Path to repository or directory to audit (defaults to current directory)",
    ),
    json_output_flag: bool = typer.Option(
        False,
        "--json",
        help="Output audit findings and coverage as JSON",
    ),
    output: Optional[Path] = typer.Option(
        None,
        "--output",
        "-o",
        help="Write output to a specified file instead of stdout",
    ),
    verbose: bool = typer.Option(
        False,
        "--verbose",
        "-v",
        help="Display detailed debugging info during scan",
    ),
) -> None:
    """Audit observability, tracing, and telemetry instrumentation across nodes and tools."""
    if not output and not json_output_flag:
        with console.status(f"[bold magenta]Auditing observability instrumentation at {path}...[/bold magenta]"):
            result = scan_repository(path, verbose=verbose)
    else:
        result = scan_repository(path, verbose=verbose)

    if json_output_flag:
        audit_json = result.observability.model_dump_json(indent=2) if result.observability else "{}"
        if output:
            output.write_text(audit_json, encoding="utf-8")
            console.print(f"[green]✔ Saved audit JSON to {output}[/green]")
        else:
            print(audit_json)
    else:
        if output:
            file_console = Console(record=True, width=120)
            print_audit_report(result, console=file_console)
            output.write_text(file_console.export_text(), encoding="utf-8")
            console.print(f"[green]✔ Saved audit report to {output}[/green]")
        else:
            print_audit_report(result, console=console)


