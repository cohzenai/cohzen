def _find_db(path_str: str) -> Path:
    p = Path(path_str).resolve()
    if p.is_file() and p.name == "executions.db":
        return p
    if (p / ".cohzen" / "executions.db").is_file():
        return p / ".cohzen" / "executions.db"
    for parent in [p, *p.parents]:
        cand = parent / ".cohzen" / "executions.db"
        if cand.is_file():
            return cand
    return p / ".cohzen" / "executions.db"


@app.command(name="init")
def init(
    path: str = typer.Argument(
        ".",
        help="Path to repository or project to initialize (defaults to current directory)",
    ),
    force: bool = typer.Option(
        False,
        "--force",
        "-f",
        help="Force re-initialization and overwrite existing manifest",
    ),
) -> None:
    """Initialize Cohzen in a project: generate static manifest, create local telemetry store, and enable auto-recording."""
    project_dir = Path(path).resolve()
    cohzen_dir = project_dir / ".cohzen"
    manifest_path = cohzen_dir / "manifest.json"
    db_path = cohzen_dir / "executions.db"

    if manifest_path.is_file() and not force:
        console.print(f"[yellow]Cohzen already initialized at {project_dir}[/yellow]")
        console.print("[dim]Use --force to re-scan architecture and overwrite manifest.[/dim]")
        return

    cohzen_dir.mkdir(parents=True, exist_ok=True)

    with console.status(f"[bold cyan]Scanning repository architecture at {project_dir}...[/bold cyan]"):
        result = scan_repository(str(project_dir))

    manifest_json = format_json(result)
    manifest_path.write_text(manifest_json, encoding="utf-8")

    # Initialize SQLite store
    SQLiteExecutionStore(db_path=db_path)

    # Add .cohzen/ to .gitignore
    gitignore_path = project_dir / ".gitignore"
    git_dir = project_dir / ".git"
    if gitignore_path.exists() or git_dir.exists():
        current_content = gitignore_path.read_text(encoding="utf-8") if gitignore_path.exists() else ""
        if ".cohzen" not in current_content:
            with open(gitignore_path, "a", encoding="utf-8") as f:
                if current_content and not current_content.endswith("\n"):
                    f.write("\n")
                f.write("# Cohzen execution telemetry\n.cohzen/\n")

    # Create sitecustomize.py for zero-effort auto-instrumentation
    sitecustomize_path = project_dir / "sitecustomize.py"
    hook_code = (
        "# Cohzen auto-instrumentation hook (generated by cz init)\n"
        "try:\n"
        "    import cz.execution\n"
        "    cz.execution.install()\n"
        "except Exception:\n"
        "    pass\n"
    )
    if not sitecustomize_path.exists():
        sitecustomize_path.write_text(hook_code, encoding="utf-8")
    else:
        existing = sitecustomize_path.read_text(encoding="utf-8")
        if "cz.execution" not in existing:
            with open(sitecustomize_path, "a", encoding="utf-8") as f:
                f.write(f"\n{hook_code}")

    # Install cohzen.pth into active venv site-packages if present
    for candidate in [project_dir, *project_dir.parents]:
        for sp in candidate.glob(".venv/lib/python*/site-packages"):
            try:
                (sp / "cohzen.pth").write_text("import cz.execution; cz.execution.install()\n", encoding="utf-8")
            except Exception:
                pass

    # Invoke scan and audit reports
    print_console_report(result, console=console)
    print_audit_report(result, console=console)

    console.print(f"\n[bold green]✔ Cohzen initialized at {project_dir}[/bold green]")
    console.print(
        f"  • Manifest: [cyan].cohzen/manifest.json[/cyan] ({result.total_graphs} graphs, {result.total_nodes} nodes, {len(result.tool_definitions)} tools)"
    )
    console.print("  • Telemetry DB: [cyan].cohzen/executions.db[/cyan]")
    console.print("  • Auto-recording: [cyan]sitecustomize.py[/cyan]")
    console.print("  • Added [cyan].cohzen/[/cyan] to [cyan].gitignore[/cyan]")
    console.print("\n[dim]Run your application normally:[/dim]")
    console.print("  [bold]python app.py[/bold]")
    console.print("\n[dim]Then inspect recorded executions:[/dim]")
    console.print("  [bold]cz runs[/bold]\n")


@app.command(name="deinit")
def deinit(
    path: str = typer.Argument(
        ".",
        help="Path to repository or project to deinitialize (defaults to current directory)",
    ),
    force: bool = typer.Option(
        False,
        "--force",
        "-f",
        help="Force de-initialization without confirmation",
    ),
) -> None:
    """Deinitialize Cohzen in a project: delete all changes made by the cz init command."""
    project_dir = Path(path).resolve()
    removed_items: list[str] = []

    # 1. Remove .cohzen directory
    cohzen_dir = project_dir / ".cohzen"
    if cohzen_dir.exists():
        if cohzen_dir.is_dir():
            shutil.rmtree(cohzen_dir)
        else:
            cohzen_dir.unlink()
        removed_items.append("Removed [cyan].cohzen/[/cyan] directory")

    # 2. Clean sitecustomize.py
    sitecustomize_path = project_dir / "sitecustomize.py"
    if sitecustomize_path.is_file():
        content = sitecustomize_path.read_text(encoding="utf-8")
        if "cz.execution" in content or "Cohzen auto-instrumentation hook" in content:
            cleaned = re.sub(
                r"\n?# Cohzen auto-instrumentation hook \(generated by cz init\)\n"
                r"try:\n"
                r"    import cz\.execution\n"
                r"    cz\.execution\.install\(\)\n"
                r"except Exception:\n"
                r"    pass\n?",
                "",
                content,
            )
            if "cz.execution" in cleaned:
                cleaned = re.sub(
                    r"\n?try:\s*\n\s*import cz\.execution\s*\n\s*cz\.execution\.install\(\)\s*\nexcept Exception:\s*\n\s*pass\n?",
                    "",
                    cleaned,
                )
            if not cleaned.strip():
                sitecustomize_path.unlink()
                removed_items.append("Removed [cyan]sitecustomize.py[/cyan]")
            else:
                sitecustomize_path.write_text(cleaned.strip() + "\n", encoding="utf-8")
                removed_items.append("Removed auto-recording hook from [cyan]sitecustomize.py[/cyan]")

    # 3. Clean .gitignore
    gitignore_path = project_dir / ".gitignore"
    if gitignore_path.is_file():
        content = gitignore_path.read_text(encoding="utf-8")
        if ".cohzen" in content:
            lines = content.splitlines()
            new_lines = []
            for line in lines:
                stripped = line.strip()
                if stripped == "# Cohzen execution telemetry":
                    continue
                if stripped in (".cohzen", ".cohzen/", "/.cohzen", "/.cohzen/"):
                    continue
                new_lines.append(line)

            cleaned = "\n".join(new_lines).strip()
            if not cleaned:
                gitignore_path.unlink()
                removed_items.append("Removed [cyan].gitignore[/cyan]")
            else:
                gitignore_path.write_text(cleaned + "\n", encoding="utf-8")
                removed_items.append("Removed [cyan].cohzen/[/cyan] from [cyan].gitignore[/cyan]")

    # 4. Remove cohzen.pth from virtualenv site-packages
    pth_removed = False
    for candidate in [project_dir, *project_dir.parents]:
        for pattern in [
            ".venv/lib/python*/site-packages/cohzen.pth",
            ".venv/Lib/site-packages/cohzen.pth",
            "venv/lib/python*/site-packages/cohzen.pth",
            "venv/Lib/site-packages/cohzen.pth",
        ]:
            for pth in candidate.glob(pattern):
                try:
                    if pth.is_file():
                        pth.unlink()
                        pth_removed = True
                except Exception:
                    pass
    if pth_removed:
        removed_items.append("Removed [cyan]cohzen.pth[/cyan] from virtual environment")

    if not removed_items:
        console.print(f"[yellow]No Cohzen initialization found at {project_dir}[/yellow]")
        return

    console.print(f"\n[bold green]✔ Cohzen deinitialized at {project_dir}[/bold green]")
    for item in removed_items:
        console.print(f"  • {item}")
    console.print()


@app.command(name="runs")
def list_runs(
    path: str = typer.Argument(
        ".",
        help="Path to repository or directory containing .cohzen (defaults to current directory)",
    ),
    limit: int = typer.Option(
        50,
        "--limit",
        "-n",
        help="Maximum number of executions to list",
    ),
    json_output_flag: bool = typer.Option(
        False,
        "--json",
        help="Output executions as JSON",
    ),
) -> None:
    """List recorded graph executions."""
    db_path = _find_db(path)
    if not db_path.is_file():
        console.print("[yellow]No execution store found.[/yellow]")
        console.print(f"[dim]Expected database at: {db_path}[/dim]")
        console.print("[dim]Run [bold]cz init[/bold] to initialize Cohzen for this project.[/dim]")
        return

    store = SQLiteExecutionStore(db_path=db_path)
    executions = store.list_executions(limit=limit)

    if json_output_flag:
        data = [e.model_dump(mode="json") for e in executions]
        print(json.dumps(data, indent=2, default=str))
    else:
        print_executions_table(executions, console=console)


@app.command(name="run")
def view_run(
    execution_id: str = typer.Argument(
        ...,
        help="Execution ID or prefix (e.g. a82f91)",
    ),
    path: str = typer.Option(
        ".",
        "--path",
        "-p",
        help="Path to repository or directory containing .cohzen",
    ),
    json_output_flag: bool = typer.Option(
        False,
        "--json",
        help="Output execution details and spans as JSON",
    ),
    verbose: bool = typer.Option(
        False,
        "--verbose",
        "-v",
        help="Display full inputs, outputs, prompts, LLMs, and tools",
    ),
    details: bool = typer.Option(
        False,
        "--details",
        "-d",
        help="Deep-dive inspection showing full inputs, outputs, prompts, LLMs, and tools",
    ),
    waterfall: bool = typer.Option(
        True,
        "--waterfall/--no-waterfall",
        "-w",
        help="Display timeline waterfall chart",
    ),
    tree: bool = typer.Option(
        True,
        "--tree/--no-tree",
        "-t",
        help="Display hierarchical execution tree",
    ),
    node: Optional[str] = typer.Option(
        None,
        "--node",
        help="Inspect only a specific node name",
    ),
    view: bool = typer.Option(
        False,
        "--view",
        help="Open interactive execution waterfall and trace visualizer in browser",
    ),
) -> None:
    """View detailed execution flow, timeline waterfall, spans, and metrics for a specific run."""
    db_path = _find_db(path)
    if not db_path.is_file():
        console.print(f"[bold red]Error:[/bold red] No execution store found at {db_path}")
        return

    store = SQLiteExecutionStore(db_path=db_path)
    execution = store.get_execution(execution_id)
    if not execution:
        console.print(f"[bold red]Error:[/bold red] Execution [yellow]{execution_id}[/yellow] not found in store.")
        return

    spans = store.get_spans(execution.id)

    if view:
        viewer_path = open_execution_in_browser(execution, spans)
        console.print(f"[bold green]✔ Opened execution trace and waterfall in browser ({viewer_path})[/bold green]")
        return

    if json_output_flag:
        data = {
            "execution": execution.model_dump(mode="json"),
            "spans": [s.model_dump(mode="json") for s in spans],
        }
        print(json.dumps(data, indent=2, default=str))
    else:
        print_execution_detail(
            execution,
            spans,
            console=console,
            verbose=verbose,
            show_waterfall=waterfall,
            show_tree=tree,
            show_details=details or verbose,
            node_filter=node,
        )


