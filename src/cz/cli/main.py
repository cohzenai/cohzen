def _find_db(path_str: str) -> Path:
    p = Path(path_str).resolve()
    if p.is_file() and p.name == "executions.db":
        return p
    if (p / ".cohzen" / "executions.db").is_file():
        return p / ".cohzen" / "executions.db"
    for parent in [p, *p.parents]:
        cand = parent / ".cohzen" / "executions.db"
        if cand.is_file():
            return cand
    return p / ".cohzen" / "executions.db"


def _clean_sitecustomize(sitecustomize_path: Path) -> bool:
    if not sitecustomize_path.is_file():
        return False
    content = sitecustomize_path.read_text(encoding="utf-8")
    if "cz.execution" not in content and "Cohzen auto-instrumentation hook" not in content:
        return False
    cleaned = re.sub(
        r"\n?# Cohzen auto-instrumentation hook \(generated by cz init\)\n"
        r"try:\n"
        r"    import cz\.execution\n"
        r"    cz\.execution\.install\(\)\n"
        r"except Exception:\n"
        r"    pass\n?",
        "",
        content,
    )
    if "cz.execution" in cleaned:
        cleaned = re.sub(
            r"\n?try:\s*\n\s*import cz\.execution\s*\n\s*cz\.execution\.install\(\)\s*\nexcept Exception:\s*\n\s*pass\n?",
            "",
            cleaned,
        )
    if not cleaned.strip():
        sitecustomize_path.unlink()
    else:
        sitecustomize_path.write_text(cleaned.strip() + "\n", encoding="utf-8")
    return True


def _target_site_packages(python: str) -> tuple[Path | None, str | None]:
    """Inspect one requested interpreter without importing its application code."""
    probe = (
        "import importlib.util,json,site,sysconfig;"
        "purelib = sysconfig.get_path('purelib');"
        "sites = site.getsitepackages() if hasattr(site, 'getsitepackages') else [];"
        "target = purelib if purelib in sites else (sites[0] if sites else purelib);"
        "print(json.dumps({'site': target, 'langgraph': bool(importlib.util.find_spec('langgraph')), "
        "'cohzen': bool(importlib.util.find_spec('cz'))}))"
    )
    try:
        output = subprocess.check_output([python, "-c", probe], text=True, stderr=subprocess.PIPE)
        data = json.loads(output)
        site_dir = data.get("site")
        if not site_dir:
            return None, "could not determine site-packages"
        warnings: list[str] = []
        if not data.get("langgraph"):
            warnings.append("LangGraph is not importable in the target Python environment; capture will stay off.")
        if not data.get("cohzen"):
            warnings.append("Cohzen is not importable in the target Python environment; install Cohzen there first.")
        return Path(site_dir), " ".join(warnings) or None
    except (OSError, subprocess.CalledProcessError, json.JSONDecodeError) as exc:
        return None, f"could not inspect target Python ({exc})"


def _hook_path(python: str) -> tuple[Path | None, str | None]:
    site_packages, warning = _target_site_packages(python)
    return (site_packages / "cohzen_startup.pth" if site_packages else None), warning


def _write_config(path: Path, enabled: bool | None = None) -> None:
    if not path.exists():
        path.write_text(DEFAULT_CONFIG, encoding="utf-8")
    if enabled is not None:
        lines = path.read_text(encoding="utf-8").splitlines()
        updated = [
            f"enabled = {'true' if enabled else 'false'}" if line.startswith("enabled =") else line for line in lines
        ]
        path.write_text("\n".join(updated) + "\n", encoding="utf-8")


@app.command(name="init")
def init(
    path: str = typer.Argument(
        ".",
        help="Path to repository or project to initialize (defaults to current directory)",
    ),
    yes: bool = typer.Option(False, "--yes", "-y", help="Apply without interactive confirmation"),
    python: str = typer.Option(sys.executable, "--python", help="Python environment that receives the startup hook"),
) -> None:
    """Enable local always-on capture for this project."""
    project_dir = Path(path).resolve()
    cohzen_dir = project_dir / ".cohzen"
    manifest_path = cohzen_dir / "manifest.json"
    db_path = cohzen_dir / "executions.db"
    config_path = cohzen_dir / "config.toml"
    hook_path, warning = _hook_path(python)
    planned = [
        f"create or modify {config_path}",
        f"create or modify {manifest_path}",
        f"create or modify {db_path}",
        f"create or modify {project_dir / '.gitignore'}",
    ]
    if hook_path:
        planned.append(f"create or modify {hook_path}")
        legacy_hook = hook_path.parent / "cohzen.pth"
        if legacy_hook.is_file():
            planned.append(f"migrate legacy hook: remove {legacy_hook}")
    else:
        planned.append("skip startup hook because the target Python could not be inspected")
    legacy_sitecustomize = project_dir / "sitecustomize.py"
    if legacy_sitecustomize.is_file():
        content = legacy_sitecustomize.read_text(encoding="utf-8")
        if "cz.execution" in content or "Cohzen auto-instrumentation hook" in content:
            planned.append(f"migrate legacy hook: clean {legacy_sitecustomize}")

    console.print("Cohzen will:")
    for item in planned:
        console.print(f"  • {item}")
    if warning:
        console.print(f"[yellow]Warning:[/yellow] {warning}")
    if not yes and not typer.confirm("Continue?", default=False):
        raise typer.Abort()

    cohzen_dir.mkdir(parents=True, exist_ok=True)
    _write_config(config_path)

    with console.status(f"[bold cyan]Scanning repository architecture at {project_dir}...[/bold cyan]"):
        result = scan_repository(str(project_dir))

    manifest_json = format_json(result)
    manifest_path.write_text(manifest_json, encoding="utf-8")

    # Initialize SQLite store
    SQLiteExecutionStore(db_path=db_path)

    if hook_path:
        hook_path.parent.mkdir(parents=True, exist_ok=True)
        hook_path.write_text(
            'import sys; exec("try:\\n    import cz._startup; cz._startup.start()\\nexcept Exception:\\n    pass")\n',
            encoding="utf-8",
        )
        legacy_hook = hook_path.parent / "cohzen.pth"
        if legacy_hook.is_file():
            legacy_hook.unlink()
            console.print(f"  • Migrated legacy hook: removed {legacy_hook}")
    if _clean_sitecustomize(legacy_sitecustomize):
        console.print(f"  • Migrated legacy hook: cleaned {legacy_sitecustomize}")

    # Add .cohzen/ to .gitignore
    gitignore_path = project_dir / ".gitignore"
    git_dir = project_dir / ".git"
    if gitignore_path.exists() or git_dir.exists():
        current_content = gitignore_path.read_text(encoding="utf-8") if gitignore_path.exists() else ""
        if ".cohzen" not in current_content:
            with open(gitignore_path, "a", encoding="utf-8") as f:
                if current_content and not current_content.endswith("\n"):
                    f.write("\n")
                f.write("# Cohzen execution telemetry\n.cohzen/\n")

    # Print topology report for slim init output
    print_topology_report(result, console=console)

    console.print(f"\n[bold green]✔ Cohzen initialized at {project_dir}[/bold green]")
    console.print(
        f"  • Manifest: [cyan].cohzen/manifest.json[/cyan] ({result.total_graphs} graphs, {result.total_nodes} nodes, {len(result.tool_definitions)} tools)"
    )
    console.print("  • Telemetry DB: [cyan].cohzen/executions.db[/cyan]")
    if hook_path:
        console.print(f"  • Startup hook: [cyan]{hook_path}[/cyan]")
    console.print("  • Added [cyan].cohzen/[/cyan] to [cyan].gitignore[/cyan]")
    console.print(
        "\n[dim]Capture is enabled for eligible local LangGraph runs. One-off capture remains available:[/dim]"
    )
    console.print("  [bold]cz capture -- python app.py[/bold]")
    console.print("\n[dim]Then inspect recorded executions:[/dim]")
    console.print("  [bold]cz runs[/bold]\n")


@app.command(
    name="capture",
    context_settings={"allow_extra_args": True, "ignore_unknown_options": True},
)
def capture(
    ctx: typer.Context,
    path: str = typer.Option(".", "--path", "-p", help="Project directory that owns .cohzen/"),
) -> None:
    """Run a supplied command with Cohzen runtime capture enabled for that process only."""
    command = list(ctx.args)
    if command and command[0] == "--":
        command.pop(0)
    if not command:
        raise typer.BadParameter("Provide a command after '--', for example: cz capture -- python app.py")

    project_dir = Path(path).resolve()
    console.print("[bold yellow]Cohzen capture runs the supplied command and therefore runs your code.[/bold yellow]")
    console.print(f"[dim]Command: {' '.join(command)}[/dim]")
    with tempfile.TemporaryDirectory(prefix="cohzen-capture-") as bootstrap_dir:
        bootstrap_path = Path(bootstrap_dir) / "sitecustomize.py"
        bootstrap_path.write_text(
            "# Temporary Cohzen capture bootstrap; removed when this command exits.\n"
            "from cz.execution import install\n"
            "install()\n",
            encoding="utf-8",
        )
        env = os.environ.copy()
        env["PYTHONPATH"] = os.pathsep.join(filter(None, [bootstrap_dir, env.get("PYTHONPATH", "")]))
        try:
            result = subprocess.run(command, cwd=project_dir, env=env, check=False)
        except FileNotFoundError:
            console.print(f"[bold red]Error:[/bold red] Command not found: '{command[0]}'")
            raise typer.Exit(code=127)
        except PermissionError:
            console.print(f"[bold red]Error:[/bold red] Permission denied: '{command[0]}'")
            raise typer.Exit(code=126)
        except OSError as exc:
            console.print(f"[bold red]Error:[/bold red] Failed to execute '{command[0]}': {exc}")
            raise typer.Exit(code=1)
    if result.returncode:
        raise typer.Exit(code=result.returncode)


@app.command(name="status")
def status(path: str = typer.Argument(".", help="Project directory")) -> None:
    """Show effective always-on capture settings for a project."""
    project = find_project(Path(path))
    if not project:
        console.print("[yellow]Cohzen is not initialized in this path.[/yellow]")
        return
    config = load_config(project)
    hook_path, warning = _hook_path(sys.executable)
    console.print(f"Project: {project}")
    console.print(f"Enabled: {config['enabled']}")
    console.print(f"Capture in CI: {config['capture_in_ci']}")
    console.print(f"Startup hook: {hook_path if hook_path and hook_path.is_file() else 'not installed'}")
    console.print(
        f"Retention: {config['max_runs']} runs, {config['max_age_days']} days, {config['max_payload_bytes']} bytes/payload"
    )
    if warning:
        console.print(f"[yellow]Warning:[/yellow] {warning}")


def _set_capture_enabled(path: str, enabled: bool) -> None:
    project = find_project(Path(path))
    if not project:
        raise typer.BadParameter("No .cohzen marker found; run 'cz init' first.")
    _write_config(project / ".cohzen" / "config.toml", enabled=enabled)
    console.print(f"Cohzen capture {'enabled' if enabled else 'disabled'} for {project}")


@app.command(name="on")
def enable_capture(path: str = typer.Argument(".", help="Project directory")) -> None:
    """Enable always-on capture for a project."""
    _set_capture_enabled(path, True)


@app.command(name="off")
def disable_capture(path: str = typer.Argument(".", help="Project directory")) -> None:
    """Disable always-on capture for a project."""
    _set_capture_enabled(path, False)


@app.command(name="deinit")
def deinit(
    path: str = typer.Argument(
        ".",
        help="Path to repository or project to deinitialize (defaults to current directory)",
    ),
    yes: bool = typer.Option(False, "--yes", "--force", "-f", help="Delete without interactive confirmation"),
    keep_data: bool = typer.Option(
        False, "--keep-data", help="Keep executions.db while removing configuration and hooks"
    ),
    python: str = typer.Option(sys.executable, "--python", help="Python environment that received the startup hook"),
) -> None:
    """Deinitialize Cohzen in a project: delete all changes made by the cz init command."""
    project_dir = Path(path).resolve()
    cohzen_dir = project_dir / ".cohzen"
    config_path = cohzen_dir / "config.toml"
    manifest_path = cohzen_dir / "manifest.json"
    db_path = cohzen_dir / "executions.db"
    sitecustomize_path = project_dir / "sitecustomize.py"
    gitignore_path = project_dir / ".gitignore"
    hook_path, _ = _hook_path(python)

    planned: list[str] = []
    if cohzen_dir.exists():
        if keep_data and cohzen_dir.is_dir():
            if config_path.exists():
                planned.append(f"remove {config_path}")
            if manifest_path.exists():
                planned.append(f"remove {manifest_path}")
            if db_path.exists():
                planned.append(f"retain {db_path}")
        else:
            planned.append(f"remove {cohzen_dir}")

    if sitecustomize_path.is_file():
        content = sitecustomize_path.read_text(encoding="utf-8")
        if "cz.execution" in content or "Cohzen auto-instrumentation hook" in content:
            planned.append(f"remove Cohzen hook from {sitecustomize_path}")

    if gitignore_path.is_file() and ".cohzen" in gitignore_path.read_text(encoding="utf-8"):
        planned.append(f"remove .cohzen/ from {gitignore_path}")

    discovered_pths: list[Path] = []
    if hook_path and hook_path.is_file():
        discovered_pths.append(hook_path)
    if hook_path and (hook_path.parent / "cohzen.pth").is_file():
        discovered_pths.append(hook_path.parent / "cohzen.pth")
    for candidate in [project_dir, *project_dir.parents]:
        for pattern in [
            ".venv/lib/python*/site-packages/cohzen*.pth",
            ".venv/Lib/site-packages/cohzen*.pth",
            "venv/lib/python*/site-packages/cohzen*.pth",
            "venv/Lib/site-packages/cohzen*.pth",
        ]:
            for pth in candidate.glob(pattern):
                if pth.is_file() and pth not in discovered_pths:
                    discovered_pths.append(pth)

    for pth in discovered_pths:
        planned.append(f"remove startup hook {pth}")

    if not planned:
        console.print(f"[yellow]No Cohzen initialization found at {project_dir}[/yellow]")
        return

    console.print("Cohzen will:")
    for item in planned:
        console.print(f"  • {item}")

    if not yes and not typer.confirm("Continue?", default=False):
        raise typer.Abort()

    removed_items: list[str] = []

    # 1. Remove or clean .cohzen directory
    if cohzen_dir.exists():
        if keep_data and cohzen_dir.is_dir():
            for item in (config_path, manifest_path):
                if item.exists():
                    item.unlink()
            removed_items.append("Removed Cohzen configuration; retained [cyan]executions.db[/cyan]")
        elif cohzen_dir.is_dir():
            shutil.rmtree(cohzen_dir)
            removed_items.append("Removed [cyan].cohzen/[/cyan] directory")
        else:
            cohzen_dir.unlink()
            removed_items.append("Removed [cyan].cohzen[/cyan]")

    # 2. Clean sitecustomize.py
    if _clean_sitecustomize(sitecustomize_path):
        removed_items.append(
            "Removed [cyan]sitecustomize.py[/cyan]"
            if not sitecustomize_path.exists()
            else "Removed auto-recording hook from [cyan]sitecustomize.py[/cyan]"
        )

    # 3. Clean .gitignore
    if gitignore_path.is_file():
        content = gitignore_path.read_text(encoding="utf-8")
        if ".cohzen" in content:
            lines = content.splitlines()
            new_lines = []
            for line in lines:
                stripped = line.strip()
                if stripped == "# Cohzen execution telemetry":
                    continue
                if stripped in (".cohzen", ".cohzen/", "/.cohzen", "/.cohzen/"):
                    continue
                new_lines.append(line)

            cleaned = "\n".join(new_lines).strip()
            if not cleaned:
                gitignore_path.unlink()
                removed_items.append("Removed [cyan].gitignore[/cyan]")
            else:
                gitignore_path.write_text(cleaned + "\n", encoding="utf-8")
                removed_items.append("Removed [cyan].cohzen/[/cyan] from [cyan].gitignore[/cyan]")

    for pth in discovered_pths:
        try:
            if pth.is_file():
                pth.unlink()
                removed_items.append(f"Removed [cyan]{pth.name}[/cyan] ({pth})")
        except OSError:
            pass

    if not removed_items:
        console.print(f"[yellow]No Cohzen initialization found at {project_dir}[/yellow]")
        return

    console.print(f"\n[bold green]✔ Cohzen deinitialized at {project_dir}[/bold green]")
    for item in removed_items:
        console.print(f"  • {item}")
    console.print()


@app.command(name="runs")
def list_runs(
    path: str = typer.Argument(
        ".",
        help="Path to repository or directory containing .cohzen (defaults to current directory)",
    ),
    limit: int = typer.Option(
        50,
        "--limit",
        "-n",
        help="Maximum number of executions to list",
    ),
    json_output_flag: bool = typer.Option(
        False,
        "--json",
        help="Output executions as JSON",
    ),
) -> None:
    """List recorded graph executions."""
    db_path = _find_db(path)
    if not db_path.is_file():
        console.print("[yellow]No execution store found.[/yellow]")
        console.print(f"[dim]Expected database at: {db_path}[/dim]")
        console.print("[dim]Run [bold]cz init[/bold] to initialize Cohzen for this project.[/dim]")
        return

    store = SQLiteExecutionStore(db_path=db_path)
    executions = store.list_executions(limit=limit)

    if json_output_flag:
        data = [e.model_dump(mode="json") for e in executions]
        print(json.dumps(data, indent=2, default=str))
    else:
        print_executions_table(executions, console=console)


@app.command(name="run")
def view_run(
    execution_id: str = typer.Argument(
        ...,
        help="Execution ID or prefix (e.g. a82f91)",
    ),
    path: str = typer.Option(
        ".",
        "--path",
        "-p",
        help="Path to repository or directory containing .cohzen",
    ),
    json_output_flag: bool = typer.Option(
        False,
        "--json",
        help="Output execution details and spans as JSON",
    ),
    verbose: bool = typer.Option(
        False,
        "--verbose",
        "-v",
        help="Display inputs, outputs, errors, and entity IDs for each span",
    ),
) -> None:
    """View detailed execution flow, spans, and metrics for a specific run."""
    db_path = _find_db(path)
    if not db_path.is_file():
        console.print(f"[bold red]Error:[/bold red] No execution store found at {db_path}")
        raise typer.Exit(code=1)

    store = SQLiteExecutionStore(db_path=db_path)
    execution = store.get_execution(execution_id)
    if not execution:
        console.print(f"[bold red]Error:[/bold red] Execution [yellow]{execution_id}[/yellow] not found in store.")
        raise typer.Exit(code=1)

    spans = store.get_spans(execution.id)

    if json_output_flag:
        data = {
            "execution": execution.model_dump(mode="json"),
            "spans": [s.model_dump(mode="json") for s in spans],
        }
        print(json.dumps(data, indent=2, default=str))
    else:
        print_execution_detail(execution, spans, console=console, verbose=verbose)


@app.command(name="scan")
def scan(
    path: str = typer.Argument(
        ".",
        help="Path to repository or directory to scan (defaults to current directory)",
    ),
    format: OutputFormat = typer.Option(
        OutputFormat.TABLE,
        "--format",
        "-f",
        help="Output format: table (rich interactive terminal), json (system manifest), or mermaid (diagram)",
    ),
    mermaid: bool = typer.Option(
        False,
        "--mermaid",
        help="Shortcut to output Mermaid diagram (equivalent to -f mermaid)",
    ),
    json_output_flag: bool = typer.Option(
        False,
        "--json",
        help="Shortcut to output Cohzen Manifest JSON (equivalent to -f json)",
    ),
    output: Path | None = typer.Option(
        None,
        "--output",
        "-o",
        help="Write output to a specified file instead of stdout",
    ),
    verbose: bool = typer.Option(
        False,
        "--verbose",
        "-v",
        help="Display detailed debugging info during scan",
    ),
    view: bool = typer.Option(
        False,
        "--view",
        help="Open an interactive graphical visualizer in the default browser",
    ),
) -> None:
    """Scan a codebase to reconstruct LangGraph architecture and produce a system manifest."""
    if mermaid:
        format = OutputFormat.MERMAID
    elif json_output_flag:
        format = OutputFormat.JSON

    if format == OutputFormat.TABLE and not output and not view:
        with console.status(f"[bold cyan]Scanning repository for LangGraph architectures at {path}...[/bold cyan]"):
            result = scan_repository(path, verbose=verbose)
    else:
        result = scan_repository(path, verbose=verbose)

    if view:
        from cz.formatters.viewer import open_in_browser

        viewer_path = open_in_browser(result)
        console.print(
            f"[bold green]✔ Opened interactive architecture visualizer in browser ({viewer_path})[/bold green]"
        )
        return

    # Format the result
    if format == OutputFormat.TABLE:
        if output:
            file_console = Console(record=True, width=120)
            print_console_report(result, console=file_console)
            output.write_text(file_console.export_text(), encoding="utf-8")
            console.print(f"[green]✔ Saved scan table report to {output}[/green]")
        else:
            print_console_report(result, console=console)

    elif format == OutputFormat.JSON:
        json_output = format_json(result)
        if output:
            output.write_text(json_output, encoding="utf-8")
            console.print(f"[green]✔ Saved JSON manifest to {output}[/green]")
        else:
            print(json_output)

    elif format == OutputFormat.MERMAID:
        mermaid_output = format_mermaid(result)
        if output:
            output.write_text(mermaid_output, encoding="utf-8")
            console.print(f"[green]✔ Saved Mermaid diagram to {output}[/green]")
        else:
            print(mermaid_output)


@app.command(name="audit")
def audit(
    path: str = typer.Argument(
        ".",
        help="Path to repository or directory to audit (defaults to current directory)",
    ),
    json_output_flag: bool = typer.Option(
        False,
        "--json",
        help="Output audit findings and coverage as JSON",
    ),
    output: Path | None = typer.Option(
        None,
        "--output",
        "-o",
        help="Write output to a specified file instead of stdout",
    ),
    min_coverage: float | None = typer.Option(
        None,
        "--min-coverage",
        help=(
            "Minimum required agent/node instrumentation percentage (0-100). "
            "Exit code 1 if not met. Skipped with an INFO line when no nodes are found, "
            "unless --fail-on-empty is also passed."
        ),
    ),
    fail_on_missing: bool = typer.Option(
        False,
        "--fail-on-missing",
        help="Exit with code 1 if no telemetry packages or environment configurations are detected.",
    ),
    fail_on_empty: bool = typer.Option(
        False,
        "--fail-on-empty",
        help=(
            "Exit with code 1 when no agent nodes are found. "
            "By default --min-coverage is silently skipped on empty repos; "
            "this flag makes that an error instead."
        ),
    ),
    verbose: bool = typer.Option(
        False,
        "--verbose",
        "-v",
        help="Display detailed debugging info during scan",
    ),
) -> None:
    """Audit observability, tracing, and telemetry instrumentation across nodes and tools.

    Exit codes:
      0  All requested checks passed (or skipped on an empty repo without --fail-on-empty).
      1  A CI gate check failed (--min-coverage not met, --fail-on-missing triggered,
         or --fail-on-empty triggered on an empty repo).
      2  Usage / argument error (handled by Typer).
    """
    if not output and not json_output_flag:
        with console.status(f"[bold magenta]Auditing observability instrumentation at {path}...[/bold magenta]"):
            result = scan_repository(path, verbose=verbose)
    else:
        result = scan_repository(path, verbose=verbose)

    if json_output_flag:
        audit_json = result.observability.model_dump_json(indent=2) if result.observability else "{}"
        if output:
            output.write_text(audit_json, encoding="utf-8")
            console.print(f"[green]✔ Saved audit JSON to {output}[/green]")
        else:
            print(audit_json)
    else:
        if output:
            file_console = Console(record=True, width=120)
            print_audit_report(result, console=file_console)
            output.write_text(file_console.export_text(), encoding="utf-8")
            console.print(f"[green]✔ Saved audit report to {output}[/green]")
        else:
            print_audit_report(result, console=console)

    # CI / CD Gate Enforcement
    failed_reasons: list[str] = []
    obs = result.observability

    if fail_on_missing:
        if not obs or not obs.is_observability_configured:
            failed_reasons.append("No LLM observability package or environment config was detected.")

    # --fail-on-empty: fail if no agent nodes were found.
    if fail_on_empty and (not obs or obs.total_agents == 0):
        failed_reasons.append(
            "No agent nodes found in the scanned path. If this is intentional, remove --fail-on-empty."
        )

    if min_coverage is not None:
        pct = obs.agent_instrumentation_pct if obs else None
        if pct is None:
            # No nodes found — coverage is not applicable.
            # Default: skip the gate with an INFO line.
            # --fail-on-empty (handled above) is the correct flag to fail on empty repos.
            console.print(
                "[dim cyan]INFO:[/dim cyan] [dim]--min-coverage skipped: no agent nodes found "
                "in scanned path. Use --fail-on-empty to fail on empty repositories.[/dim]"
            )
        elif pct < min_coverage:
            failed_reasons.append(
                f"Agent instrumentation coverage is {pct}%, below the required threshold of {min_coverage}%."
            )

    if failed_reasons:
        for r in failed_reasons:
            console.print(f"[bold red]CI Gate Failure:[/bold red] {r}")
        raise typer.Exit(code=1)


